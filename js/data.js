    const bp = basePath || getBasePath();
    if (!imagePath) return bp + 'assets/页面通用图片/暂无图片.png';
    if (/^https?:\/\//.test(imagePath)) return imagePath;
    if (imagePath.startsWith('/')) return imagePath;
    return bp + imagePath;
